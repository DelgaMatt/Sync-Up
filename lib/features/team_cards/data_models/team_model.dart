import 'package:flutter/material.dart';

class TeamMember {
  final String name;
  final String bio;
  final String instagram;
  final String soundcloud;
  final String biopic;
  final String logo;

  const TeamMember({
    required this.name,
    required this.bio,
    required this.instagram,
    required this.soundcloud,
    required this.biopic,
    required this.logo,
  });
}

